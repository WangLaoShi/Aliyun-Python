'''
题目：一个整数，它加上100和加上268后都是一个完全平方数，请问该数是多少？
'''


# 完全平方数（或称为平方数）是指一个整数可以表示为另一个整数的平方的数。
# 也就是说，如果有一个整数 \( n \)，存在一个整数 \( m \)，使得 \( n = m^2 \)，那么 \( n \) 就是一个完全平方数。
#
# 例如：
#
# - \( 1 = 1^2 \)
# - \( 4 = 2^2 \)
# - \( 9 = 3^2 \)
# - \( 16 = 4^2 \)
# - \( 25 = 5^2 \)
#
# 这些都是完全平方数。

import math

for x in range(10000):
    n = math.sqrt(x + 100)
    m = math.sqrt(x + 268)
    if n % 1 == 0 and m % 1 == 0:
        print(x)
